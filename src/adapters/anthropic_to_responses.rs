    #[test]
    fn regenerated_first_message_env_block_restores_first_seen_text() {
        let cache = FirstMessageCache::new(8);
        let live = convert_request_with_caches(
            replay_request("env block v1", &["turn reminder", "live nudge"]),
            None,
            Some(&cache),
        )
        .expect("live");
        // A new CLI process regenerates the environment block (memory index
        // edit): the replay restores the first-seen bytes.
        let resumed = convert_request_with_caches(
            replay_request("env block v2 (edited memory index)", &["turn reminder", "live nudge"]),
            None,
            Some(&cache),
        )
        .expect("resumed");
        let first_user_texts = |result: &ResponsesRequest| {
            result
                .input
                .iter()
                .filter_map(|item| match item {
                    ResponseItem::Message { role, content, .. } if role == "user" => Some(
                        content
                            .iter()
                            .filter_map(|c| match c {
                                ContentItem::InputText { text } => Some(text.clone()),
                                _ => None,
                            })
                            .collect::<Vec<_>>(),
                    ),
                    _ => None,
                })
                .next()
                .unwrap_or_default()
        };
        assert_eq!(first_user_texts(&resumed), first_user_texts(&live));
    }

    #[test]
    fn aux_call_with_other_system_prompt_never_cross_restores() {
        let cache = FirstMessageCache::new(8);
        let mut aux = replay_request("conversation snippet for titling", &["turn reminder", "live nudge"]);
        aux.system = Some(AnthropicSystemContent::Text(
            "You are naming a coding session.".to_string(),
        ));
        convert_request_with_caches(aux, None, Some(&cache)).expect("aux");
        // The main conversation under the same session id starts afterwards:
        // its first environment block must NOT be restored to the aux text.
        let main = convert_request_with_caches(
            replay_request("env block v1", &["turn reminder", "live nudge"]),
            None,
            Some(&cache),
        )
        .expect("main");
        let texts: Vec<String> = main
            .input
            .iter()
            .filter_map(|item| match item {
                ResponseItem::Message { role, content, .. } if role == "user" => Some(
                    content
                        .iter()
                        .filter_map(|c| match c {
                            ContentItem::InputText { text } => Some(text.clone()),
                            _ => None,
                        })
                        .collect::<Vec<_>>()
                        .join("\n"),
                ),
                _ => None,
            })
            .collect();
        assert!(texts.iter().any(|t| t.contains("env block v1")));
        assert!(!texts.iter().any(|t| t.contains("conversation snippet")));
    }
