    fn replay_request(env_text: &str, system_tail: &[&str]) -> AnthropicRequest {
        let mut system_blocks = vec![
            AnthropicContentBlock::Text {
                text: "turn reminder".to_string(),
            },
            AnthropicContentBlock::Text {
                text: "live nudge".to_string(),
            },
        ];
        system_blocks.truncate(system_tail.len());
        AnthropicRequest {
            model: "claude-3-5-sonnet-20241022".to_string(),
            max_tokens: Some(1024),
            system: Some(AnthropicSystemContent::Text("Base instructions.".to_string())),
            messages: vec![
                AnthropicMessage {
                    role: "user".to_string(),
                    content: AnthropicContent::Blocks(vec![
                        AnthropicContentBlock::Text {
                            text: env_text.to_string(),
                        },
                        AnthropicContentBlock::Text {
                            text: "the actual task".to_string(),
                        },
                    ]),
                },
                AnthropicMessage {
                    role: "assistant".to_string(),
                    content: AnthropicContent::Text("working".to_string()),
                },
                AnthropicMessage {
                    role: "system".to_string(),
                    content: AnthropicContent::Blocks(system_blocks),
                },
                AnthropicMessage {
                    role: "user".to_string(),
                    content: AnthropicContent::Text("continue".to_string()),
                },
            ],
            tools: None,
            tool_choice: None,
            stream: true,
            temperature: None,
            top_p: None,
            top_k: None,
            stop_sequences: None,
            metadata: Some(json!({"user_id": "{\"session_id\":\"00000000-0000-0000-0000-000000000001\"}"})),
            thinking: None,
            output_config: None,
        }
    }

    fn system_message_texts(result: &ResponsesRequest) -> Vec<String> {
        result
            .input
            .iter()
            .filter_map(|item| match item {
                ResponseItem::Message { role, content, .. } if role == "system" => Some(
                    content
                        .iter()
                        .filter_map(|c| match c {
                            ContentItem::OutputText { text } => Some(text.clone()),
                            _ => None,
                        })
                        .collect::<Vec<_>>()
                        .join("\n"),
                ),
                _ => None,
            })
            .collect()
    }

    #[test]
    fn dropped_system_message_tail_restores_first_seen_blocks() {
        let cache = SystemMessageCache::new(8);
        let live = convert_request_with_caches(
            replay_request("env block", &["turn reminder", "live nudge"]),
            Some(&cache),
            None,
        )
        .expect("live");
        // The replay drops the trailing nudge block: the gateway restores the
        // canonical first-seen list, so upstream bytes match the live turn.
        let replayed = convert_request_with_caches(
            replay_request("env block", &["turn reminder"]),
            Some(&cache),
            None,
        )
        .expect("replay");
        assert_eq!(
            system_message_texts(&replayed),
            system_message_texts(&live)
        );
    }

